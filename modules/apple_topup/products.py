def get_product(lot_id):
    if lot_id is None:
        return None

    product = PRODUCTS.get(str(lot_id))
    if not product:
        return None

    product = dict(product)
    product["lot_id"] = str(lot_id)
    product["items"] = [dict(item) for item in product.get("items", [])]
    product["quantity"] = sum(
        int(item["quantity"]) for item in product["items"]
    )

    if len(product["items"]) == 1:
        product["fazercards_card_id"] = product["items"][0]["card_id"]

    return product
